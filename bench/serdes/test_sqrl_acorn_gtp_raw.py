"""Measure PRBS errors on an Acorn raw GTP link, with optional PMA loopback."""

import argparse
import time

from litex import RemoteClient


PRBS_MODES = {"prbs7": 0b01, "prbs15": 0b10, "prbs31": 0b11}
NEAR_END_PMA_LOOPBACK = 0b010
RX_PRBS_PAUSE = 0b100
COUNTER_MASK = 0xffffffff


class SerDes:
    def __init__(self, regs, number):
        prefix = f"serdes{number}_"
        for name, csr in regs.d.items():
            if name.startswith(prefix):
                setattr(self, name[len(prefix):], csr)
        required = ("raw_status", "raw_rx_bitslip_request", "tx_prbs_config",
                    "rx_prbs_config", "rx_prbs_errors", "loopback")
        missing = [name for name in required if not hasattr(self, name)]
        if missing:
            raise ValueError(f"SerDes{number} is missing raw GTP CSRs: {', '.join(missing)}")

    def wait_ready(self, timeout):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            status = self.raw_status.read()
            if status & 0b11 == 0b11:
                if not (status & (1 << 2)):
                    raise RuntimeError("RX bit slip is not supported; rebuild with RX buffer bypassed")
                return
            time.sleep(0.1)
        raise TimeoutError("GTP did not become TX/RX ready")

    def configure(self, mode, external=False):
        self.loopback.write(0 if external else NEAR_END_PMA_LOOPBACK)
        self.tx_prbs_config.write(PRBS_MODES[mode])
        self.rx_prbs_config.write(PRBS_MODES[mode])

    def measure_errors(self, mode, duration, settle):
        # Reset the accumulated error counter, let the checker settle, then
        # pause around each read to avoid racing its clock-domain counter.
        self.rx_prbs_config.write(0)
        time.sleep(0.05)
        self.rx_prbs_config.write(PRBS_MODES[mode])
        time.sleep(settle)
        self.rx_prbs_config.write(PRBS_MODES[mode] | RX_PRBS_PAUSE)
        time.sleep(0.01)
        before = self.rx_prbs_errors.read()
        self.rx_prbs_config.write(PRBS_MODES[mode])
        time.sleep(duration)
        self.rx_prbs_config.write(PRBS_MODES[mode] | RX_PRBS_PAUSE)
        time.sleep(0.01)
        after = self.rx_prbs_errors.read()
        self.rx_prbs_config.write(PRBS_MODES[mode])
        return (after - before) & COUNTER_MASK

    def bitslip(self):
        self.raw_rx_bitslip_request.write(1)

    def unconfigure(self):
        self.rx_prbs_config.write(0)
        self.tx_prbs_config.write(0)
        self.loopback.write(0)


def run(csr_csv, port, serdes_number, mode, duration, settle, phases, ready_timeout, external):
    wb = RemoteClient(csr_csv=csr_csv, port=port)
    wb.open()
    serdes = None
    try:
        serdes = SerDes(wb.regs, serdes_number)
        serdes.wait_ready(ready_timeout)
        serdes.configure(mode, external=external)
        link_mode = "external link" if external else "near-end PMA loopback"
        print(f"{link_mode} enabled; sweeping {phases} relative RX bit-slip phases")
        if external:
            print("The far end must transmit the selected PRBS polynomial into this receiver.")
        results = []
        for phase in range(phases):
            errors = serdes.measure_errors(mode, duration, settle)
            results.append(errors)
            print(f"phase {phase:2d}: {errors:10d} errored PRBS words in {duration:g} s")
            if phase + 1 < phases:
                serdes.bitslip()
                time.sleep(settle)
        minimum = min(results)
        best = [i for i, errors in enumerate(results) if errors == minimum]
        print(f"Lowest observed count: {minimum} at relative phase(s) {', '.join(map(str, best))}")
        if len(best) == phases:
            print("All phases tied; PRBS checking did not identify a unique word boundary.")
    finally:
        if serdes is not None:
            serdes.unconfigure()
        wb.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csr-csv", default="sqrl_acorn_pcs.csv", help="CSR CSV generated by sqrl_acorn_gtp_raw.py")
    parser.add_argument("--port", type=int, default=1234, help="LiteX server port (default: 1234)")
    parser.add_argument("--serdes", type=int, default=0, help="SerDes index (default: 0)")
    parser.add_argument("--mode", choices=PRBS_MODES, default="prbs7", help="PRBS polynomial")
    parser.add_argument("--duration", type=float, default=0.25, help="Measurement time per phase in seconds")
    parser.add_argument("--settle", type=float, default=0.1, help="PRBS checker settle time in seconds")
    parser.add_argument("--phases", type=int, default=20, help="Number of successive bit-slip phases")
    parser.add_argument("--ready-timeout", type=float, default=10.0, help="Wait for GTP readiness")
    parser.add_argument("--external", action="store_true",
        help="Use an external raw link instead of enabling internal PMA loopback")
    args = parser.parse_args()
    if args.duration <= 0 or args.duration > 10:
        parser.error("--duration must be greater than 0 and at most 10 seconds")
    if args.settle < 0 or not 1 <= args.phases <= 20 or args.ready_timeout <= 0:
        parser.error("--settle must be non-negative, --phases must be 1..20, and --ready-timeout must be positive")
    run(args.csr_csv, args.port, args.serdes, args.mode, args.duration,
        args.settle, args.phases, args.ready_timeout, args.external)


if __name__ == "__main__":
    main()
