"""Check 64b/66b PCS block lock over the Acorn raw GTP PMA loopback."""

import argparse
import time

from litex import RemoteClient


NEAR_END_PMA_LOOPBACK = 0b010


class PCSLink:
    def __init__(self, regs, number):
        prefix = f"serdes{number}_"
        for name, csr in regs.d.items():
            if name.startswith(prefix):
                setattr(self, name[len(prefix):], csr)
        self.pcs_status = regs.d.get("main_pcs_status", regs.d.get("pcs_status"))
        required = ("raw_status", "loopback")
        missing = [name for name in required if not hasattr(self, name)]
        if self.pcs_status is None:
            missing.append("main_pcs_status")
        if missing:
            raise ValueError(f"SerDes{number} is missing PCS CSRs: {', '.join(missing)}")

    def wait_ready(self, timeout):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if self.raw_status.read() & 0b11 == 0b11:
                return
            time.sleep(0.05)
        raise TimeoutError("GTP did not become TX/RX ready")

    def wait_block_lock(self, timeout):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            status = self.pcs_status.read()
            if status & 0b001:
                if status & 0b110:
                    raise RuntimeError(f"PCS adapter reported an error (status=0x{status:x})")
                return status
            time.sleep(0.01)
        status = self.pcs_status.read()
        raise TimeoutError(f"64b/66b block lock not acquired (PCS status=0x{status:x})")


def run(csr_csv, port, serdes_number, ready_timeout, lock_timeout):
    wb = RemoteClient(csr_csv=csr_csv, port=port)
    wb.open()
    pcs = None
    try:
        pcs = PCSLink(wb.regs, serdes_number)
        pcs.wait_ready(ready_timeout)
        pcs.loopback.write(NEAR_END_PMA_LOOPBACK)
        status = pcs.wait_block_lock(lock_timeout)
        print(f"64b/66b block lock acquired (PCS status=0x{status:x})")
    finally:
        if pcs is not None:
            pcs.loopback.write(0)
        wb.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csr-csv", default="sqrl_acorn_pcs.csv", help="CSR CSV generated by the PCS bench")
    parser.add_argument("--port", type=int, default=1234, help="LiteX server port (default: 1234)")
    parser.add_argument("--serdes", type=int, default=0, help="SerDes index (default: 0)")
    parser.add_argument("--ready-timeout", type=float, default=10.0, help="Wait for GTP readiness")
    parser.add_argument("--lock-timeout", type=float, default=5.0, help="Wait for PCS block lock")
    args = parser.parse_args()
    if args.ready_timeout <= 0 or args.lock_timeout <= 0:
        parser.error("timeouts must be positive")
    run(args.csr_csv, args.port, args.serdes, args.ready_timeout, args.lock_timeout)


if __name__ == "__main__":
    main()
